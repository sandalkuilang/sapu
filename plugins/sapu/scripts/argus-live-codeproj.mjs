// Headers and digests.

/** A header line: the generator, the taste bar's version when one is stamped (older suites have none), the digest. */
const HEADER = /argus-live codegen [0-9]+(?:, taste-bar ([0-9]+))?, digest ([0-9a-f]{64})/;
const sha256 = (s) => createHash("sha256").update(s).digest("hex");
/** The digest of `body` judged against bar `bar`: the version joins it, so a header naming another bar is not this body's. */
const digestOf = (body, bar) => sha256(bar === null ? body : `taste-bar ${bar}\n${body}`);

/**
 * `body` (the file's text) with its header line put in at line `at`: `// <what>` (or `# <what>`, or a JSON
 * `"//"` member), naming the generator, the taste bar's version `bar` (the plugin's) and the sha256 of that
 * version and the body without the line (spec §20.3: a suite judged against an older bar is stale).
 */
export function withHeader(body, { what, style = "//", at = 0, bar = loadBar().version }) {
  const digest = digestOf(body, bar);
  const words = `Generated by sapu (argus-live codegen ${CODEGEN_VERSION}, taste-bar ${bar}, digest ${digest}) ${what}: do not edit; smoke propose regenerates it.`;
  const line = style === "json" ? `  "//": ${JSON.stringify(words)},` : `${style} ${words}`;
  const lines = body.split("\n");
  lines.splice(at, 0, line);
  return lines.join("\n");
}

/**
 * A generated file's text → `{digest, ok, bar}`: the digest its header names (null without one), whether it is its
 * body's (with the bar version the header names), and that version (null in a header from before the taste bar).
 */
export function headerDigest(text) {
  const lines = String(text).split("\n");
  const i = lines.findIndex((l) => HEADER.test(l));
  if (i < 0) return { digest: null, ok: false, bar: null };
  const m = HEADER.exec(lines[i]);
  const bar = m[1] === undefined ? null : Number(m[1]);
  lines.splice(i, 1);
  return { digest: m[2], ok: digestOf(lines.join("\n"), bar) === m[2], bar };
}

